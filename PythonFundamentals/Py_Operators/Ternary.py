##Ternary operator allows you to assign the value if one condition is true or else it will return false

#Question:Assign the value "WEEKEND!" if the number is higher than 5, otherwise "Workday":
num=6;
x="WEEKEND!" if num>5 else "Workday"
print(x)

##Ternary operator can be used in longer statement

x="FRI" if num==5 else "SAT" if num==6 else "SUN" if num==7 else "WEEKDAY"
print(x)
