##To insert a character or string in already present string we use escape character followed by "\"
text="I am an software engineer \professional\ and I studied Computer science"
print(text)

text2="I am an software engineer \'professional\' and I studied Computer science"
print(text2)

text3="I am an software engineer \\(professional) and I studied Computer science"
print(text3)

text4="I am an software engineer (professional) and \n I studied Computer science"
print(text4)

text5="I am an software engineer (professional) and\rI studied Computer science"
print(text5)

text6="I am an software engineer (professional) and\tI studied Computer science"
print(text6)

text7="I am an software engineer (professional) and \bI studied Computer science"
print(text7)

text8="I am an software engineer (professional) and \fI studied Computer science"
print(text8)

text9="\110\145\154\154\157"
print(text9)

txt10 = "\x48\x65\x6c\x6c\x6f"
print(txt10)